package commands

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/sipeed/picoclaw/pkg/config"
	"github.com/sipeed/picoclaw/pkg/providers"
)

// ModelOption is a selectable model as shown to the user.
//
// Index is the 1-based position in configuration order. /list models and
// /switch model both render and accept the same index, so numbering must come
// from a single place: CollectModelOptions.
type ModelOption struct {
	Index    int
	Name     string
	Provider string
}

// CollectModelOptions returns the selectable models for the current config, in
// configuration order.
//
// Virtual entries (generated by multi-key expansion) are hidden, and duplicate
// model_name entries are collapsed: several entries may share one alias for
// load balancing, and an index must always resolve to a single switch target.
func CollectModelOptions(cfg *config.Config) []ModelOption {
	if cfg == nil {
		return nil
	}

	defaultProvider := strings.TrimSpace(cfg.Agents.Defaults.Provider)
	if defaultProvider == "" {
		defaultProvider = "openai"
	}

	options := make([]ModelOption, 0, len(cfg.ModelList))
	seen := make(map[string]struct{}, len(cfg.ModelList))
	for _, model := range cfg.ModelList {
		if model == nil || model.IsVirtual() {
			continue
		}

		name := strings.TrimSpace(model.ModelName)
		if name == "" {
			continue
		}
		if _, duplicate := seen[name]; duplicate {
			continue
		}
		seen[name] = struct{}{}

		provider := strings.TrimSpace(model.Provider)
		if provider == "" {
			provider, _ = providers.SplitModelProviderAndID(model.Model, defaultProvider)
		} else {
			provider = providers.NormalizeProvider(provider)
		}

		options = append(options, ModelOption{
			Index:    len(options) + 1,
			Name:     name,
			Provider: provider,
		})
	}

	return options
}

// FormatModelOptions renders the numbered model list shared by /list models and
// the bare /switch model reply.
func FormatModelOptions(options []ModelOption) string {
	if len(options) == 0 {
		return "No models configured"
	}

	lines := make([]string, 0, len(options))
	for _, option := range options {
		lines = append(lines, fmt.Sprintf("%d. %s (Provider: %s)", option.Index, option.Name, option.Provider))
	}
	return "Configured Models:\n" + strings.Join(lines, "\n")
}

// ResolveModelOption maps user input to a configured model name.
//
// Accepted input, in priority order: the 1-based index from /list models, the
// exact model name, or an unambiguous case-insensitive prefix.
//
// It returns candidates as a non-empty list only when the input is an ambiguous
// prefix, so callers can distinguish "ambiguous" from "unknown" and suggest the
// matching names instead of a bare error.
func ResolveModelOption(options []ModelOption, value string) (name string, candidates []string) {
	value = strings.TrimSpace(value)
	if value == "" || len(options) == 0 {
		return "", nil
	}

	if index, err := strconv.Atoi(value); err == nil {
		for _, option := range options {
			if option.Index == index {
				return option.Name, nil
			}
		}
		return "", nil
	}

	for _, option := range options {
		if option.Name == value {
			return option.Name, nil
		}
	}

	lowered := strings.ToLower(value)
	for _, option := range options {
		if strings.ToLower(option.Name) == lowered {
			return option.Name, nil
		}
	}

	for _, option := range options {
		if strings.HasPrefix(strings.ToLower(option.Name), lowered) {
			candidates = append(candidates, option.Name)
		}
	}

	switch len(candidates) {
	case 0:
		return "", nil
	case 1:
		return candidates[0], nil
	default:
		return "", candidates
	}
}
